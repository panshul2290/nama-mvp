// Codes whose detail (after "code: ") is worth showing, e.g. which documents are missing.
const WITH_DETAIL = new Set(["documents_incomplete", "insufficient_fill_credit", "wallet_not_empty", "invalid_value"]);

export function errorCode(error: { message?: string } | null | undefined): string | null {
  if (!error?.message) return null;
  return Object.keys(MESSAGES).sort((a, b) => b.length - a.length).find((code) => error.message!.includes(code)) ?? null;
}

/** UI copy for an RPC error; lang "ar" gives the Arabic wording (a detail after "code:" stays as sent). */
export function friendlyError(error: { message?: string } | null | undefined, lang: "en" | "ar" = "en"): string {
  const code = errorCode(error);
  const text = (c: string) => (lang === "ar" ? MESSAGES_AR[c] : undefined) ?? MESSAGES[c];
  if (code && WITH_DETAIL.has(code)) {
    const detail = error?.message?.split(`${code}:`)[1]?.trim();
    return detail ? `${text(code)} ${detail}.` : text(code);
  }
  return code ? text(code) : (error?.message ?? (lang === "ar" ? "حدث خطأ ما." : "Something went wrong."));
}

