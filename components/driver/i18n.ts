export function useErrText() {
  const { lang } = useLang();
  return useCallback(
    (error: { message?: string } | null | undefined) => {
      const code = errorCode(error);
      return lang === "ar" && code && AR_ERRORS[code] ? AR_ERRORS[code] : friendlyError(error);
    },
    [lang],
  );
}

